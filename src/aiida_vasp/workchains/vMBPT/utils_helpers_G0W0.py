#Helper: element → max available ENMAX

def get_encut_from_potcar_mapping(potential_mapping: dict) -> float:
    """
    Determine ENCUT from POTCAR mapping.
    Parameters
    potential_mapping : dict
        Example: { "Si": "Si_sv_GW", "O":  "O_GW" }
    Returns Maximum ENMAX (eV) across all species. """
    
    def _max_enmax_for_element(element: str) -> float:
        """  Return the maximum ENMAX available for a given element, regardless of POTCAR flavor.   """
        candidates = [ enmax for potcar, enmax in POTCAR_ENMAX.items()
                       if potcar == element or potcar.startswith(f"{element}_")   ]
        if not candidates:
            raise ValueError(f"No ENMAX data available for element '{element}'")
        return max(candidates)  
    
    enmax_values = []
    for element, potcar_name in potential_mapping.items():
        if potcar_name in POTCAR_ENMAX:
            enmax = POTCAR_ENMAX[potcar_name]
        else:
            # fallback: use max ENMAX available for this element
            enmax = _max_enmax_for_element(element)
        enmax_values.append(enmax)
    return max(enmax_values)









